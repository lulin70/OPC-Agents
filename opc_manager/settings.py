    """Email SMTP server configuration.

    Attributes:
        host: SMTP server hostname
        port: SMTP server port (typically 465 for SSL, 587 for TLS)
        username: Authentication username
        password: Authentication password (sensitive field)
        tls: Whether to use TLS encryption
        from_email: Sender email address
    """

    host: str = ""
    port: int = 587
    username: str = ""
    password: str = ""
    tls: bool = True
    from_email: str = ""


