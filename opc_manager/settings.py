    def update_llm(self, **kwargs) -> bool:
        """Update LLM settings with validation and persistence.

        Args:
            **kwargs: Field names and values to update (provider, api_key, etc.)

        Returns:
            True if update succeeded (always returns True currently,
            may add validation logic later)

        Side effects:
            - Updates os.environ for immediate LLM client use
            - Triggers registered callbacks
            - Persists to disk
        """
        valid_fields = {k for k in dir(LLMSettings) if not k.startswith("_")}
        for k, v in kwargs.items():
            if k in valid_fields:
                setattr(self._llm, k, v)
            else:
                logger.warning("Unknown LLM setting field: %s", k)

        self._save_to_disk()
        self._notify_callbacks("llm")

        if kwargs.get("api_key"):
            self._store_sensitive_key("MOKA_API_KEY", kwargs["api_key"])
        if kwargs.get("base_url"):
            self._store_sensitive_key("MOKA_API_BASE", kwargs["base_url"])
        if kwargs.get("model"):
            self._store_sensitive_key("MOKA_MODEL", kwargs["model"])

        return True

