"""
Settings Manager — v0.2.1 统一设置中心

提供运行时可修改的用户设置，支持持久化到JSON文件。
所有敏感信息通过SecureKeyStore加密存储。

设计原则：
- 与 ConfigManager（只读env）互补：ConfigManager管系统配置，SettingsManager管用户偏好
- 线程安全单例模式：全局唯一实例，支持多线程并发访问
- 敏感字段掩码：导出时自动脱敏，防止密钥泄露
- 原子写入：使用临时文件+rename保证数据一致性

Usage:
    from opc_manager.settings import get_settings, SettingsManager, SettingsCategory

    settings = get_settings()
    settings.update_llm(provider="moka", api_key="sk-xxx", model="moka/claude-sonnet-4-6")
    print(settings.llm.provider)  # "moka"
"""

